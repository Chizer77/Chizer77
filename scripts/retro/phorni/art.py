# 中间姿势的左侧长发外另生出一截短支，沿主发束边缘逐行去除。
MAIN_HAIR_LEFT = (10, 10, 10, 9, 9, 9, 8, 8, 8, 8, 8, 7, 7, 7)


def precise_wing_mask(size, pose_index):
    result = Image.new('L', size)
    draw = ImageDraw.Draw(result)
    for wing_rows in (SCREEN_LEFT_WING_ROWS, SCREEN_RIGHT_WING_ROWS):
        for row, left, right in wing_rows[pose_index]:
            draw.line((left, row, right, row), fill=255)
    return result


def remove_short_hair_branch(body, pose_index):
    if pose_index != 2:
        return body
    for row, left in enumerate(MAIN_HAIR_LEFT, 48):
        body.paste((0, 0, 0, 0), (5, row, left, row + 1))
    return body
